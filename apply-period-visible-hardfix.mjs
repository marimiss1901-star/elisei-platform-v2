import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const patchRoot=path.dirname(fileURLToPath(import.meta.url));
const projectRoot=process.cwd();
const candidates=['frontend/index.html','frontend_v2/index.html','client/index.html','web/index.html','app/index.html','index.html'];
const indexRel=candidates.find(p=>fs.existsSync(path.join(projectRoot,p)));
if(!indexRel)throw new Error('Не найден index.html frontend. Запусти установщик из корня репозитория.');
const indexFile=path.join(projectRoot,indexRel);
const frontRoot=path.dirname(indexFile);
const publicDir=path.join(frontRoot,'public');
fs.mkdirSync(publicDir,{recursive:true});
for(const name of ['elisei-period-hardfix.js','elisei-period-hardfix.css'])fs.copyFileSync(path.join(patchRoot,'payload/public',name),path.join(publicDir,name));
const backup=indexFile+'.period-5.3.16-backup';if(!fs.existsSync(backup))fs.copyFileSync(indexFile,backup);
let html=fs.readFileSync(indexFile,'utf8');
html=html.replace(/\s*<link[^>]+elisei-period-(?:hardfix|runtime|visible)[^>]*>\s*/gi,'\n').replace(/\s*<script[^>]+elisei-period-(?:hardfix|runtime|visible)[^>]*><\/script>\s*/gi,'\n');
const injection='\n  <!-- ELISEI 5.3.16 GLOBAL PERIOD HARDFIX -->\n  <link rel="stylesheet" href="/elisei-period-hardfix.css?v=5.3.16">\n  <script src="/elisei-period-hardfix.js?v=5.3.16"></script>\n';
if(/<\/head>/i.test(html))html=html.replace(/<\/head>/i,injection+'</head>');else html=injection+html;
fs.writeFileSync(indexFile,html);
fs.writeFileSync(path.join(projectRoot,'ELISEI_BUILD_5_3_16_PERIOD_HARDFIX.txt'),['ELISEI 5.3.16','VISIBLE BAR: INDEX.HTML INJECTION','TRANSPORT: FETCH + XHR BEFORE APP','ROUTE /app REQUIRES RENDER REWRITE /* -> /index.html','Applied: '+new Date().toISOString()].join('\n'));
console.log('ELISEI 5.3.16 установлен.');
console.log('Frontend index: '+indexRel);
console.log('Assets: '+path.relative(projectRoot,publicDir));
console.log('После build на странице будет видна метка версии 5.3.16.');
